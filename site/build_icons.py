def fetch(name, cache):
    p = cache / (name + ".svg")
    if not p.exists():
        r = subprocess.run(["curl", "-sfL", "-o", str(p), URL % name], capture_output=True)
        if r.returncode != 0:
            sys.exit("could not fetch %s (curl %d)" % (name, r.returncode))
    return p.read_text(encoding="utf-8")


def inner(svg):
    body = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1)
    body = re.sub(r'<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*/>', "", body)
    if re.search(r"<(script|style|image|use|foreignObject)|\son\w+=", body, re.I):
        sys.exit("unexpected content in a Tabler file")
    return re.sub(r"\s+", " ", body).replace(" />", "/>").strip()


def main():
    cache = pathlib.Path(tempfile.gettempdir()) / ("tabler-" + VERSION)
    cache.mkdir(exist_ok=True)
    lines = ['<!-- icons:start · Tabler Icons %s outline, MIT, generated by site/build_icons.py, do not edit by hand -->' % VERSION]
    for sid, name in MAP.items():
        lines.append('<symbol id="%s" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="%s" '
                     'stroke-linecap="round" stroke-linejoin="round">%s</symbol>' % (sid, STROKE, inner(fetch(name, cache))))
    lines.append("<!-- icons:end -->")
    page = SITE / "index.html"
    html = page.read_text(encoding="utf-8")
    new, n = re.subn(r"<!-- icons:start.*?<!-- icons:end -->", lambda m: "\n".join(lines), html, flags=re.S)
    if n != 1:
        sys.exit("markers not found in index.html")
    page.write_text(new, encoding="utf-8")
    print("%d icons written to %s" % (len(MAP), page.relative_to(SITE.parent)))


if __name__ == "__main__":
    main()
