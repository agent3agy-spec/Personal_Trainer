"""build_icons.py · writes the icon sprite in site/index.html from Tabler outline icons (MIT, Paweł Kuna).

    python3 site/build_icons.py

Each app id maps to one Tabler name. The SVG files are fetched with curl from jsdelivr at a pinned
version, flattened into <symbol>s (stroke currentColor, one stroke width) and written between the
<!-- icons:start --> and <!-- icons:end --> markers. Nothing is linked at run time, so the page loads no
icon font and no stylesheet but Google Fonts. To change an icon, change its name below and run again.
"""
import pathlib, re, subprocess, sys, tempfile

VERSION = "3.19.0"
URL = "https://cdn.jsdelivr.net/npm/@tabler/icons@%s/icons/outline/%%s.svg" % VERSION
STROKE = "1.75"
SITE = pathlib.Path(__file__).resolve().parent

